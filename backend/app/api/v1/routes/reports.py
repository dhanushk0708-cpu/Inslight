@router.get("/{report_id}/download")
def download_report(
    report_id: str,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    """Download generated report file with ownership and access validation."""
    report = ReportRepository.get_by_id(db, report_id=report_id, user_id=user.id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found or access denied.")

    if not os.path.exists(report.file_path):
        raise HTTPException(status_code=404, detail="Report file not found on disk.")

    media_types = {
        "pdf": "application/pdf",
        "excel": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        "csv": "text/csv"
    }
    ext = "pdf" if report.report_format == "pdf" else ("xlsx" if report.report_format == "excel" else "csv")
    download_filename = f"{report.name.replace(' ', '_')}.{ext}"

    return FileResponse(
        path=report.file_path,
        media_type=media_types.get(report.report_format, "application/octet-stream"),
        filename=download_filename
    )


@router.delete("/{report_id}")
def delete_report(
    report_id: str,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    """Delete a report from database and disk with strict ownership check."""
    report = ReportRepository.get_by_id(db, report_id=report_id, user_id=user.id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found or access denied.")

    if os.path.exists(report.file_path):
        try:
            os.remove(report.file_path)
        except Exception:
            pass

    ReportRepository.delete_report(db, report_id=report_id, user_id=user.id)
    return {"status": "success", "message": f"Report '{report.name}' deleted successfully."}
