@router.get("/schedules/{schedule_id}", response_model=ScheduledReportResponse)
def get_schedule(
    schedule_id: str,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    schedule = ReportRepository.get_scheduled_report(db, schedule_id=schedule_id, user_id=user.id)
    if not schedule:
        raise HTTPException(status_code=404, detail="Schedule not found or access denied.")
    return schedule


@router.put("/schedules/{schedule_id}", response_model=ScheduledReportResponse)
def update_schedule(
    schedule_id: str,
    req: ScheduledReportUpdateRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    data = req.model_dump(exclude_unset=True)
    if "recipients" in data and isinstance(data["recipients"], list):
        data["recipients"] = ",".join(data["recipients"])

    schedule = ReportRepository.update_scheduled_report(db, schedule_id=schedule_id, user_id=user.id, **data)
    if not schedule:
        raise HTTPException(status_code=404, detail="Schedule not found or access denied.")
    return schedule


@router.delete("/schedules/{schedule_id}")
def delete_schedule(
    schedule_id: str,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    success = ReportRepository.delete_scheduled_report(db, schedule_id=schedule_id, user_id=user.id)
    if not success:
        raise HTTPException(status_code=404, detail="Schedule not found or access denied.")
    return {"status": "success", "message": "Schedule deleted successfully."}


