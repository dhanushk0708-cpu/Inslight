@router.post("/email", response_model=EmailSendResponse)
async def email_report(
    req: EmailSendRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    """Email a generated report via Gmail API after explicit user confirmation."""
    report = ReportRepository.get_by_id(db, report_id=req.report_id, user_id=user.id)
    if not report:
        raise HTTPException(status_code=404, detail="Report not found or access denied.")

    ext = "pdf" if report.report_format == "pdf" else ("xlsx" if report.report_format == "excel" else "csv")
    attachment_name = f"{report.name.replace(' ', '_')}.{ext}"

    try:
        res = await GmailService.send_report_email(
            db=db,
            user=user,
            recipients=req.recipients,
            subject=req.subject,
            body=req.body,
            file_path=report.file_path,
            attachment_name=attachment_name,
            cc_recipients=req.cc_recipients
        )
        ReportRepository.update_email_status(
            db=db,
            report_id=report.id,
            user_id=user.id,
            status="sent",
            gmail_message_id=res.get("gmail_message_id"),
            recipients=",".join(req.recipients),
            subject=req.subject
        )
        AuditService.log_action(
            db=db,
            user_id=user.id,
            action="email_send",
            resource_type="report",
            resource_id=report.id,
            status="success",
            metadata={"recipient_count": len(req.recipients)},
        )
        return EmailSendResponse(
            status="success",
            message="Report emailed successfully via Gmail API.",
            gmail_message_id=res.get("gmail_message_id"),
            recipients=req.recipients,
            delivered_at=res.get("delivered_at")
        )
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except Exception as e:
        ReportRepository.update_email_status(
            db=db,
            report_id=report.id,
            user_id=user.id,
            status="failed",
            recipients=",".join(req.recipients),
            subject=req.subject
        )
        AuditService.log_action(
            db=db,
            user_id=user.id,
            action="email_send",
            resource_type="report",
            resource_id=report.id,
            status="failure",
            metadata={"error": str(e)[:120]},
        )
        NotificationService.create_notification(
            db=db,
            user_id=user.id,
            category="email",
            title="Email Delivery Failed",
            message=f"Failed to send report '{report.name}' via Gmail: {str(e)[:120]}",
            resource_type="report",
            resource_id=report.id,
        )
        raise HTTPException(status_code=502, detail=f"Failed to send email: {str(e)}")


# ━━━━━━━━ 2. SCHEDULED REPORTS (Precedes parameterized routes) ━━━━━━━━

@router.post("/schedules", response_model=ScheduledReportResponse)
def create_schedule(
    req: ScheduledReportCreateRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    """Configure a new automated report schedule (weekly/monthly)."""
    now = datetime.now(timezone.utc)
    delta = timedelta(days=7) if req.frequency == "weekly" else timedelta(days=30)
    next_run = now + delta

    schedule = ReportRepository.create_scheduled_report(
        db=db,
        user_id=user.id,
        dataset_id=req.dataset_id,
        report_name=req.report_name,
        frequency=req.frequency,
        report_format=req.report_format,
        recipients=",".join(req.recipients),
        email_subject=req.email_subject,
        email_body=req.email_body,
        next_run_at=next_run,
        is_active=req.is_active
    )
    return schedule


