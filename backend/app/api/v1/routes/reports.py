# ━━━━━━━━ 1. REPORT GENERATION & LISTING ━━━━━━━━

@router.post("/generate", response_model=ReportResponse)
async def generate_report(
    req: ReportGenerateRequest,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user)
):
    """Generate a PDF, Excel, or CSV report from actual analytics results."""
    try:
        report = await ReportService.generate_report(
            db=db,
            user=user,
            title=req.title,
            report_format=req.report_format,
            dataset_id=req.dataset_id,
            report_type=getattr(req, "report_type", "executive") or "executive",
            include_anomalies=req.include_anomalies,
            custom_query_data=req.custom_query_data
        )
        AuditService.log_action(
            db=db,
            user_id=user.id,
            action="report_generate",
            resource_type="report",
            resource_id=report.id,
            status="success",
            metadata={"format": req.report_format, "title": req.title},
        )
        NotificationService.create_notification(
            db=db,
            user_id=user.id,
            category="report",
            title=f"Report Ready: {req.title}",
            message=f"Your {req.report_format.upper()} report '{req.title}' has been generated and is ready for download.",
            resource_type="report",
            resource_id=report.id,
        )
        return report
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Report generation failed: {str(e)}")


